def compute_sharpe(
    returns: pd.Series | pd.DataFrame,
    *,
    risk_free_annual: float | None = None,
    trading_days: int = 252,
) -> float:
    """Annualised Sharpe ratio.

    Parameters
    ----------
    returns : pd.Series or pd.DataFrame
        Daily (or per‑horizon) returns.  If Series, a single series Sharpe.
        If DataFrame, Sharpe is computed per column.
    risk_free_annual : float, optional
        Annual risk‑free rate.  Defaults to ``Settings.risk_free_rate``.
    trading_days : int
        Number of trading days for annualisation (default 252).

    Returns
    -------
    float
        Annualised Sharpe ratio.
    """
    from src.config import get_settings

    rf = risk_free_annual or get_settings().risk_free_rate

    if isinstance(returns, pd.DataFrame):
        # Compute Sharpe per column
        excess = returns.mean() - rf / trading_days
        std = returns.std()
        if std == 0 or np.isfinite(std) is False:
            return 0.0
        return (excess * trading_days) / (std * np.sqrt(trading_days))

    # Series case
    if returns.std() == 0 or not np.isfinite(returns.std()):
        return 0.0
    excess = returns.mean() - rf / trading_days
    return (excess * trading_days) / (returns.std() * np.sqrt(trading_days))


def compute_sortino(
    returns: pd.Series | pd.DataFrame,
    *,
    risk_free_annual: float | None = None,
    trading_days: int = 252,
) -> float:
    """Annualised Sortino ratio (downside deviation only).

    Parameters
    ----------
    returns : pd.Series or pd.DataFrame
        Daily (or per‑horizon) returns.
    risk_free_annual : float, optional
        Annual risk‑free rate.  Defaults to ``Settings.risk_free_rate``.
    trading_days : int
        Number of trading days for annualisation (default 252).

    Returns
    -------
    float
        Annualised Sortino ratio.
    """
    from src.config import get_settings

    rf = risk_free_annual or get_settings().risk_free_rate

    if isinstance(returns, pd.DataFrame):
        excess_mean = returns.mean() - rf / trading_days
        downside = returns[returns < 0].std()
        if downside == 0 or not np.isfinite(downside):
            return 0.0 if excess_mean == 0 else np.inf if excess_mean > 0 else -np.inf
        return (excess_mean * trading_days) / (downside * np.sqrt(trading_days))

    # Series case
    if returns.std() == 0 and returns.mean() - rf / trading_days == 0:
        return 0.0
    excess_mean = returns.mean() - rf / trading_days
    downside = returns[returns < 0].std()
    if downside == 0 or not np.isfinite(downside):
        return 0.0 if excess_mean == 0 else np.inf if excess_mean > 0 else -np.inf
    return (excess_mean * trading_days) / (downside * np.sqrt(trading_days))


def compute_max_drawdown(
    equity_curve: pd.Series,
) -> dict[str, float]:
    """Calculate maximum drawdown from an equity curve.

    Parameters
    ----------
    equity_curve : pd.Series
        NAV or portfolio value over time (monotonically indexed).

    Returns
    -------
    dict
        ``{"max_drawdown": float, "peak_date": str|None, "trough_date": str|None,
        "recovery_date": str|None}``  Dates are ISO format strings if the index
        is datetime, otherwise None.
    """
    if equity_curve.empty:
        return {"max_drawdown": 0.0, "peak_date": None, "trough_date": None, "recovery_date": None}

    # Peak-to-trough drawdown
    roll_max = equity_curve.cummax()
    drawdown = (equity_curve - roll_max) / roll_max

    max_dd = drawdown.min()
    # Find the peak date (first occurrence of the max value before the trough)
    trough_idx = drawdown.idxmin()
    peak_before_trough = equity_curve.loc[:trough_idx].idxmax()

    # Find recovery: first date after trough where equity exceeds peak
    recovery_idx = None
    if trough_idx is not None:
        peak_value = equity_curve.loc[peak_before_trough]
        after_trough = equity_curve.loc[trough_idx:]
        recovery_mask = after_trough > peak_value
        if recovery_mask.any():
            recovery_idx = recovery_mask.idxmax()

    # Format dates
    peak_date = pd.Timestamp(peak_before_trough).date().isoformat() if peak_before_trough is not None else None
    trough_date = pd.Timestamp(trough_idx).date().isoformat() if trough_idx is not None else None
    recovery_date = pd.Timestamp(recovery_idx).date().isoformat() if recovery_idx is not None else None

    return {
        "max_drawdown": float(max_dd),
        "peak_date": peak_date,
        "trough_date": trough_date,
        "recovery_date": recovery_date,
    }


def compute_metrics_from_signals(
    signals_df: pd.DataFrame,
    *,
    risk_free_annual: float | None = None,
    trading_days: int = 252,
) -> dict[str, Any]:
    """Compute full set of strategy metrics from a signals DataFrame.

    Parameters
    ----------
    signals_df : pd.DataFrame
        Output of :func:`compute_strategy_returns`.
    risk_free_annual : float, optional
        Annual risk‑free rate.  Defaults to ``Settings.risk_free_rate``.
    trading_days : int
        Number of trading days for annualisation (default 252).

    Returns
    -------
    dict
        {
            "annualized_return": float,
            "annualized_volatility": float,
            "sharpe": float,
            "sortino": float,
            "max_drawdown": dict,
            "total_trades": int,
            "n_periods": int,
        }
    """
    from src.config import get_settings

    df = signals_df.copy()
    rf = risk_free_annual or get_settings().risk_free_rate
    td = int(trading_days)

    # Ensure we have daily returns; if the input is per-horizon we annualise
    # by assuming the returns are already appropriately scaled.
    # Here we treat the ``net_return`` as per‑period returns and annualise.

    daily_returns = df["net_return"]

    # Annualised return (simple compounding assumption)
    # If we have N periods, annual return = (1 + mean_return)^(td/N) - 1
    # But for simplicity, use mean * td (simple scaling)
    mean_return = daily_returns.mean()
    annualized_return = mean_return * td

    # Annualised volatility
    annualized_volatility = daily_returns.std() * np.sqrt(td)

    sharpe = compute_sharpe(daily_returns, risk_free_annual=rf, trading_days=td)
    sortino = compute_sortino(daily_returns, risk_free_annual=rf, trading_days=td)

    # Max drawdown from equity curve
    # Build equity curve: cumulative product of (1 + net_return)
    equity = (1.0 + daily_returns).cumprod()

    max_dd_info = compute_max_drawdown(equity)

    # Count trades (signal changes from 0 to non-zero or sign change)
    n_trades = int((df["signal"] != 0).sum() / 2)  # round-trip: entry + exit

    n_periods = len(df)

    return {
        "annualized_return": float(annualized_return),
        "annualized_volatility": float(annualized_volatility),
        "sharpe": float(sharpe),
        "sortino": float(sortino),
        "max_drawdown": max_dd_info,
        "total_trades": n_trades,
        "n_periods": n_periods,
    }