"""Trading strategy metrics for walk-forward validation (Module 10).

Defines a simple rule‑based strategy, computes portfolio equity, and calculates
risk‑adjusted metrics (Sharpe, Sortino, maximum drawdown) from out‑of‑sample
returns only.  All metrics use the annualisation conventions from the project
settings (``risk_free_rate``, ``252`` trading days, ``365`` calendar days).
"""

from __future__ import annotations

import numpy as np
import pandas as pd
from typing import Any

from src.config import get_settings


# ---------------------------------------------------------------------------
# Simple trading rule
# ---------------------------------------------------------------------------

def generate_signals(
    predictions: pd.DataFrame,
    *,
    horizon: int | None = None,
    threshold: float | None = None,
) -> pd.DataFrame:
    """Generate +/-1 signal from model predictions.

    Signal rule:
    * ``signal = +1`` if ``pred_return`` > ``threshold`` (or 0 if threshold is None)
    * ``signal = -1`` if ``pred_return`` < ``-threshold``
    * ``signal = 0`` otherwise (no confidence)

    The ``threshold`` defaults to the absolute mean of ``pred_return`` across the
    test set, or can be overridden.

    Parameters
    ----------
    predictions : pd.DataFrame
        Long-format prediction frame (``PREDICTION_COLUMNS``) containing
        ``pred_return`` column.
    horizon : int, optional
        If provided, only predictions for this horizon are used.
    threshold : float, optional
        Confidence threshold for signal generation.  Defaults to ``|mean(pred_return)|``.

    Returns
    -------
    pd.DataFrame
        Input frame with a new ``signal`` column (+1, -1, or 0) aligned by row.
    """
    from src.models.baseline import PREDICTION_COLUMNS as _PREDICTION_COLUMNS

    df = predictions.copy()
    if horizon is not None:
        df = df[df["horizon"] == int(horizon)]

    pred = df["pred_return"].to_numpy(dtype="float64")

    if threshold is None:
        # Default: use |mean(pred_return)| as threshold
        threshold = float(np.mean(np.abs(pred)))

    signal = np.zeros(len(df), dtype=np.float64)
    signal[pred > threshold] = 1.0
    signal[pred < -threshold] = -1.0

    df = df.copy()
    df["signal"] = signal
    return df


# ---------------------------------------------------------------------------
# Strategy returns (with transaction costs and execution timing)
# ---------------------------------------------------------------------------

def compute_strategy_returns(
    signals: pd.DataFrame,
    *,
    transaction_cost_bps: float | None = None,
    risk_free_annual: float | None = None,
) -> pd.DataFrame:
    """Compute gross and net strategy returns from a signals DataFrame.

    The signals DataFrame should contain at least:
    * ``asset_symbol``
    * ``bar_date``
    * ``horizon``
    * ``pred_return`` (the predicted return for the horizon)
    * ``actual_return`` (the realised n+h return)
    * ``signal`` (+1, -1, or 0) generated by :func:`generate_signals`

    Strategy logic:
    * ``position`` = ``signal`` entered at the ``bar_date`` of the prediction
    * ``gross_return`` = ``position * actual_return`` (the return realised while
      holding the position for the horizon)
    * ``net_return`` = ``gross_return - transaction_cost`` per trade
    * Transaction cost is applied per round‑turn (entry + exit) in basis points.

    Execution timing assumption:
    * Signal is generated on ``bar_date`` and held for the full ``horizon``,
      then the next signal is generated.  No intra‑fold rebalancing.

    Parameters
    ----------
    signals : pd.DataFrame
        Signals DataFrame from :func:`generate_signals`.
    transaction_cost_bps : float, optional
        Transaction cost in basis points.  Defaults to
        ``Settings.transaction_cost_bps``.
    risk_free_annual : float, optional
        Annual risk‑free rate for Sharpe/Sortino.  Defaults to
        ``Settings.risk_free_rate``.

    Returns
    -------
    pd.DataFrame
        DataFrame with a ``net_return`` column and metadata columns.
    """
    settings = get_settings()
    tc_bps = transaction_cost_bps or settings.transaction_cost_bps
    rc = risk_free_annual or settings.risk_free_rate

    df = signals.copy()

    # Round-trip transaction cost: cost applies when we enter AND exit a position
    # Cost fraction = bps / 10000
    cost_frac = tc_bps / 10_000.0

    # Position is the signal value; we compute gross return as position * actual_return
    df["gross_return"] = df["signal"] * df["actual_return"]

    # Transaction cost: apply cost when signal changes sign (round-trip)
    # We detect trades by looking at consecutive non-zero signals with different signs
    # Simple approach: cost applied every time we have a non-zero signal (entry + exit)
    # More accurate: cost per trade pair (entry and exit)
    # For simplicity: cost per row where signal != 0, proportional to position size
    # Actually, let's apply cost on trade changes:
    # A "trade" occurs when signal changes from previous row (within same asset/horizon)
    # We'll compute per-asset-horizon groups

    # First, sort by asset_symbol, horizon, bar_date for proper ordering
    df = df.sort_values(["asset_symbol", "horizon", "bar_date"], kind="mergesort").reset_index(drop=True)

    # Compute trade flag: signal changes from previous row (within asset/horizon group)
    df["prev_signal"] = df.groupby(["asset_symbol", "horizon"])["signal"].shift(1)
    df["signal_changed"] = (df["signal"] != 0) & ((df["signal"] != 0) & (df["prev_signal"] != 0) & (df["signal"] != df["prev_signal"]))
    df["signal_started"] = (df["signal"] != 0) & (df["prev_signal"] == 0)

    # Apply transaction cost:
    # - Cost when a signal starts (entry)
    # - Cost when signal changes sign (round-trip exit + entry)
    # For simplicity, we charge cost per trade event (signal start or change)
    df["trade_cost"] = 0.0
    # Cost for starting a new position
    df.loc[df["signal_started"], "trade_cost"] = cost_frac
    # Cost for changing sign (round-trip)
    df.loc[df["signal_changed"], "trade_cost"] = cost_frac

    df["net_return"] = df["gross_return"] - df["trade_cost"]

    # Clean up helper columns
    df = df.drop(columns=["prev_signal", "signal_changed", "signal_started", "gross_return", "trade_cost"])

    return df


